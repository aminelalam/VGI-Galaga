"""Rasterize the bundled, licensed Vera font into the instrument HUD atlas."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

BASE = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(BASE / "fonts" / "Vera.ttf"), 48)
atlas = Image.new("RGBA", (1024, 512), (255, 255, 255, 0))
draw = ImageDraw.Draw(atlas)
top = font.getbbox("H")[1]
cap = font.getbbox("H")[3] - top
advances = []
for code in range(128):
    char = chr(code) if code >= 32 else " "
    x, y = code % 16 * 64, code // 16 * 64
    draw.text((x + 8, y + 8 - top), char, font=font, fill=(255, 255, 255, 255))
    advances.append(round(font.getlength(char) + 1.5, 4))
atlas.save(BASE / "hud" / "instrument_font.png")
header = BASE.parent / "Entrega_Amin_VGI" / "entornsGrafics" / "EntornVGI" / "RendererFont.h"
values = ",\n    ".join(", ".join(f"{v:.4f}f" for v in advances[i:i + 8]) for i in range(0, 128, 8))
header.write_text(
    "#pragma once\n// Generated by generar_fuente_hud.py from bundled Bitstream Vera.\n"
    f"namespace galaga {{\ninline constexpr float HudCapHeight = {cap}.f;\n"
    f"inline constexpr float HudAdvance[128] = {{\n    {values}\n}};\n}}\n",
    encoding="utf-8")
print(f"HUD atlas: 1024x512, cap height {cap}px; {header.name}")
